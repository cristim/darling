// CFLAGS: -lpthread
#include <pthread.h>
#include <signal.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "thread_startup_sigmask.h"

// Regression for the signal mask a new thread runs with during startup.
//
// Three things have to be true, and fixing one used to break another:
//
//   1. the startup set blocks every signal a guest handler could enter on, because
//      both signal entry paths issue a dserver RPC that aborts before the thread's
//      per-thread socket exists;
//   2. the realtime signals stay out of that set, because darlingserver uses
//      LINUX_SIGRTMIN to hold a thread and LINUX_SIGRTMIN + 1 for the accompanying
//      suspension, and a thread suspended while it starts still has to be resumable;
//   3. when the set is lifted again, the mask restored is the one the *creating*
//      thread was running with, not the one the child's own SIG_BLOCK saved while
//      the set was applied.
//
// The third is the one that is easy to get wrong and impossible to notice: on a
// platform with pthread_attr_setsigmask_np the thread is already carrying the
// startup set when darling_thread_entry blocks, so the save it takes is the startup
// set, and restoring that leaves every new thread blocked for the rest of its life,
// including on the realtime signals. So this checks the restore against the loader's
// own source as well as exercising the mask itself.
//
// Build and run, from the repository root:
//
//   clang -std=gnu11 -D_GNU_SOURCE -pthread
//       -I src/startup/mldr/include -I <dir with generated rtsig.h>
//       -o thread_startup_sigmask
//       src/startup/mldr/regressions/thread_startup_sigmask.c
//
// threads.c is only read by the test, not linked; pass its path as the first
// argument if the default path does not resolve from the current directory.
//   ./thread_startup_sigmask [path/to/elfcalls/threads.c]
//
// rtsig.h is generated by the build (the rtsig target under src/startup), and
// threads.c is only read, not linked; pass its path if the default does not resolve.

static int failures = 0;

static void check(int condition, const char* what)
{
	if (!condition) {
		fprintf(stderr, "FAIL: %s\n", what);
		failures++;
	}
}

static sigset_t observed_mask;
static volatile int observed;

static void* read_mask(void* arg)
{
	(void) arg;
	pthread_sigmask(SIG_BLOCK, NULL, &observed_mask);
	observed = 1;
	return NULL;
}

// The three-step sequence the loader performs, in the order it performs it. This
// is the behaviour check; the source check below is what ties it to the shipped
// code rather than to a copy of it.
static void check_startup_sequence(void)
{
	sigset_t inherited;
	sigset_t startup;
	sigset_t discarded;
	sigset_t saved_by_child;
	sigset_t restored;

	// Before pthread_create: the creating thread reads its own mask. This is the
	// value the child has to end up with.
	if (pthread_sigmask(SIG_BLOCK, NULL, &inherited) != 0) {
		check(0, "the creating thread can read its own mask");
		return;
	}
	check(sigismember(&inherited, SIGUSR1) == 0,
		  "nothing is blocked before the thread starts");

	darling_thread_startup_sigmask(&startup);

	// The startup set is applied, either by the kernel through the attribute before
	// the child's first instruction or by the child itself. What that saves is
	// whatever the thread already had.
	if (pthread_sigmask(SIG_BLOCK, &startup, &discarded) != 0) {
		check(0, "the startup set can be blocked");
		return;
	}
	check(sigismember(&discarded, SIGUSR1) == 0,
		  "applying the startup set saves the mask the thread already had");

	// A child already carrying the startup set blocks again while it sets its
	// socket up, as darling_thread_entry does. This save is the startup set, not
	// what the thread inherited, so it must not be the one restored.
	if (pthread_sigmask(SIG_BLOCK, &startup, &saved_by_child) != 0) {
		check(0, "the startup set can be blocked twice");
		return;
	}
	check(sigismember(&saved_by_child, SIGUSR1) == 1,
		  "a thread already carrying the startup set saves the startup set");
	check(sigismember(&saved_by_child, LINUX_SIGRTMIN) == 0,
		  "the save still leaves the realtime signals unblocked");
	check(sigismember(&saved_by_child, SIGUSR1) != sigismember(&inherited, SIGUSR1),
		  "the child's save and the inherited mask differ, so the choice matters");

	// Restoring the captured mask. SETMASK's third argument is the mask it
	// replaced, so the result is read back rather than taken from it.
	if (pthread_sigmask(SIG_SETMASK, &inherited, &restored) != 0) {
		check(0, "the captured mask can be restored");
		return;
	}
	if (pthread_sigmask(SIG_BLOCK, NULL, &restored) != 0) {
		check(0, "the current mask can be read back");
		return;
	}
	check(sigismember(&restored, SIGUSR1) == 0,
		  "restoring the captured mask unblocks what the startup set blocked");
	check(sigismember(&restored, SIGTERM) == 0,
		  "restoring the captured mask unblocks SIGTERM again");
	check(sigismember(&restored, SIGPIPE) == 0,
		  "restoring the captured mask unblocks SIGPIPE again");
}

// The sequence above is only worth anything if the loader does it, so this reads
// the shipped source and checks the restore is the captured one. Restoring the
// child's own SIG_BLOCK save compiles, runs, and leaves threads blocked forever, so
// nothing else here would notice.
static void check_loader_source(const char* path)
{
	FILE* file = fopen(path, "r");
	char line[512];
	int saw_capture = 0;
	int saw_restore_inherited = 0;
	int saw_restore_child_save = 0;

	if (file == NULL) {
		fprintf(stderr, "FAIL: could not read %s\n", path);
		failures++;
		return;
	}

	while (fgets(line, sizeof(line), file) != NULL) {
		// The creating thread captures the mask it is running with, before clone.
		if (strstr(line, "pthread_sigmask(SIG_BLOCK, NULL,") != NULL)
			saw_capture++;

		if (strstr(line, "SIG_SETMASK") == NULL)
			continue;

		// The restore has to be the captured mask.
		if (strstr(line, "inherited_sigmask") != NULL)
			saw_restore_inherited++;
		// Restoring anything else is the bug: on a platform with
		// pthread_attr_setsigmask_np that save is the startup set.
		else if (strstr(line, "old_signals") != NULL ||
			 strstr(line, "discarded") != NULL)
			saw_restore_child_save++;
	}

	fclose(file);

	check(saw_capture > 0,
		  "the loader captures the creating thread's mask before pthread_create");
	check(saw_restore_inherited > 0,
		  "the loader restores the captured mask with SIG_SETMASK");
	check(saw_restore_child_save == 0,
		  "the loader does not restore the child's own SIG_BLOCK save");
}

int main(int argc, char** argv)
{
	sigset_t mask;
	const char* source = argc > 1 ? argv[1] : "src/startup/mldr/elfcalls/threads.c";
	int i;

	darling_thread_startup_sigmask(&mask);

	// A representative set of ordinary signals has to be blocked.
	check(sigismember(&mask, SIGUSR1) == 1, "SIGUSR1 is blocked");
	check(sigismember(&mask, SIGUSR2) == 1, "SIGUSR2 is blocked");
	check(sigismember(&mask, SIGTERM) == 1, "SIGTERM is blocked");
	check(sigismember(&mask, SIGPIPE) == 1, "SIGPIPE is blocked");
	check(sigismember(&mask, SIGSEGV) == 1, "SIGSEGV is blocked");

	// The two realtime signals stay out of it.
	check(sigismember(&mask, LINUX_SIGRTMIN) == 0,
		  "LINUX_SIGRTMIN is unblocked so darlingserver can hold a starting thread");
	check(sigismember(&mask, LINUX_SIGRTMIN + 1) == 0,
		  "LINUX_SIGRTMIN + 1 is unblocked so a starting thread can be resumed");

	// The two realtime signals are the only ones left out. Comparing against what
	// sigfillset produced keeps this about the mask the loader builds rather than
	// about which slots sigfillset itself leaves alone.
	sigset_t full;
	sigfillset(&full);
	int missing_other_than_realtime = 0;
	for (i = 1; i < NSIG; i++) {
		if (sigismember(&full, i) != 1)
			continue;
		if (sigismember(&mask, i) == 1)
			continue;
		if (i == LINUX_SIGRTMIN || i == LINUX_SIGRTMIN + 1)
			continue;
		missing_other_than_realtime++;
	}
	check(missing_other_than_realtime == 0,
		  "the realtime signals are the only ones left out of the full set");

	// The set also has to reach a new thread before its first instruction, which
	// is the window the attribute closes. pthread_attr_setsigmask_np is glibc's
	// spelling; POSIX has no equivalent.
	pthread_attr_t attr;
	check(pthread_attr_init(&attr) == 0, "pthread_attr_init succeeds");
	check(pthread_attr_setsigmask_np(&attr, &mask) == 0,
		  "the mask can be set on the thread attribute");

	pthread_t thread;
	check(pthread_create(&thread, &attr, read_mask, NULL) == 0,
		  "a thread can be created with the mask on its attribute");
	pthread_join(thread, NULL);
	pthread_attr_destroy(&attr);

	check(observed == 1, "the thread observed a mask, so it ran");
	check(sigismember(&observed_mask, SIGUSR1) == 1,
		  "the thread started with SIGUSR1 blocked");
	check(sigismember(&observed_mask, LINUX_SIGRTMIN) == 0,
		  "the thread started with LINUX_SIGRTMIN unblocked");

	check_startup_sequence();
	check_loader_source(source);

	if (failures == 0)
		printf("thread startup signal mask is correct\n");
	return failures == 0 ? 0 : 1;
}
